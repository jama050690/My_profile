export function translate(lang, key) {
  const parts = key.split(".");
  let node = translations[lang];
  for (const part of parts) {
    node = node?.[part];
  }
  if (node !== undefined) return node;

  let fallback = translations.uz;
  for (const part of parts) {
    fallback = fallback?.[part];
  }
  return fallback ?? key;
}
